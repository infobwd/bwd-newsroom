import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const home=read('index.html'),gallery=read('gallery.html'),reader=read('reader.html');
const app=read('assets/app.js'),g=read('assets/gallery.js'),r=read('assets/reader.js');
const loader=read('assets/loading.js'),css=read('assets/loading.css'),styles=read('assets/styles.css');
const sw=read('sw.js');
for(const doc of [home,gallery]){
 assert.doesNotMatch(doc,/id="app-launch"/);
 assert.doesNotMatch(doc,/classList\.add\('app-launching'\)/);
 assert.match(doc,/assets\/loading\.css/);
 assert.match(doc,/assets\/loading\.js/);
 assert.match(doc,/apple-mobile-web-app-capable/);
 assert.match(doc,/rel="apple-touch-startup-image"/);
 assert.match(doc,/startup-1290x2796\.png/);
 assert.match(doc,/startup-1179x2556\.png/);
 assert.match(doc,/startup-1170x2532\.png/);
}
assert.match(home,/bwd-skel-feature/);
assert.match(home,/bwd-skel-album/);
assert.match(home,/bwd-skel-news/);
assert.match(home,/bwd-skel-book/);
assert.match(gallery,/bwd-skel-gallery/);
assert.match(reader,/id="reader-loading"/);
assert.match(app,/grid\.replaceChildren\(\);grid\.setAttribute\('aria-busy'/);
assert.match(app,/window\.BWDLoading\?\.finishLaunch\(\)/);
assert.match(g,/window\.BWDLoading\?\.finishLaunch\(\)/);
assert.match(app,/figure\.classList\.add\('bwd-page-pending'\)/);
assert.match(g,/bwd-image-pending/);
assert.match(r,/first\.onload=\(\)=>\{pending\.hidden=true;\}/);
assert.match(r,/function fail\(message\)\{\s+byId\('reader-loading'\)\.hidden=true/);
assert.doesNotMatch(loader,/setTimeout\(finishLaunch/);
assert.match(loader,/window\.BWDLoading=Object\.freeze\(\{finishLaunch\}\)/);
assert.doesNotMatch(css,/html\.app-launching \.app-launch/);
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/@keyframes bwd-skeleton-shimmer/);
assert.match(sw,/bwd-public-shell-2569-11-15-v11-share-v13/);
assert(sw.includes("'./assets/loading.css'")&&sw.includes("'./assets/loading.js'"));
const shell=sw.slice(sw.indexOf('const SHELL='),sw.indexOf('const PATHS='));
assert(!shell.includes('assets/issues/'), 'No published page images in precache');
assert(!shell.includes('assets/galleries/'), 'No Gallery images in precache');
assert(!shell.includes('data/'), 'No public data manifest in precache');
assert.match(app,/const more=document\.createElement\('details'\)/);
assert.match(app,/moreOptions\.append\(a\)/); // PDF preserved
assert.match(app,/moreOptions\.append\(downloadImage\)/);
assert.match(app,/moreOptions\.append\(copy\)/);
assert.match(app,/shareKit\.shareFiles\(issue,files\)/);
assert.match(app,/shareKit\.lineTextUrl\(issue\)/);
assert.match(app,/actions\.prepend\(read\)/);
assert.match(styles,/\.dialog-share-more-options/);
assert(!app.includes('setTimeout(()=>report('), 'No artificial share status delay');
console.log('PASS App Experience v1.2 skeleton, launch and share source contracts (not device QA)');
