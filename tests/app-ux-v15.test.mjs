import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const app=read('assets/app.js'), css=read('assets/app-shell.css');
const worker=read('sw.js'), workflow=read('.github/workflows/static-qa.yml');
const catalog=JSON.parse(read('data/catalog.json'));
const approved=catalog.issues.filter(i=>i.status==='published'&&i.visibility_approved_at&&i.approved_version&&i.published_at);
assert(approved.length>0,'approved-only catalogue fixture required');
assert.match(app,/published\.slice\(0,5\)/,'latest carousel capped at 5 real published items');
assert.match(app,/if\(cards\.length===1\)return/,'single issue has no fake pagination');
assert.match(app,/app-carousel-dot/,'dot indicator replaces previous/next buttons');
assert.doesNotMatch(app,/app-carousel-arrow/);
assert.doesNotMatch(css,/\.app-carousel-arrow/);
assert.match(app,/aria-current','true'/,'active dot position is accessible');
assert.match(app,/dot\.addEventListener\('click'/,'dots jump to a specific issue');
assert.match(app,/const AUTO_DELAY=5500, INTERACTION_PAUSE=9000/);
assert.match(app,/autoDirection\*=-1/,'carousel reverses at the edges rather than hard-jumping');
assert.match(app,/pointerdown'.*pauseForInteraction/,'manual swipe defers autoplay');
assert.match(app,/keydown'.*pauseForInteraction/,'keyboard navigation defers autoplay');
assert.match(app,/pausedByUser=!pausedByUser/,'persistent play/pause control');
assert.match(app,/play\.setAttribute\('aria-pressed'/);
assert.match(app,/visibilitychange',scheduleAuto/,'hidden tabs do not autoplay');
assert.match(app,/dialog\?\.addEventListener\('close',scheduleAuto/,'reader pauses autoplay while open');
assert.match(app,/IntersectionObserver\(entries=>/,'offscreen carousels do not advance');
assert.match(app,/intersectionRatio>=0\.45/);
assert.match(app,/hover: hover/,'touch devices are not caught in sticky hover pause');
assert.match(app,/reducedMotion\?\.matches/,'reduced motion blocks automatic motion');
assert.match(app,/play\.hidden=Boolean\(reducedMotion\?\.matches\)/);
assert.match(app,/lastIssueInputWasPointer/);
assert.match(app,/active\?\.closest\?\.\('\.app-latest-track'\)/,'touch focus is cleared after closing the issue');
assert.match(css,/\.app-latest-track:focus-visible/,'keyboard focus remains visible');
assert.match(css,/\.app-latest-track:focus:not\(:focus-visible\)/,'touch focus outline is suppressed');
assert.match(css,/\.app-carousel-dot\[aria-current='true'\]::before/);
assert.match(css,/width:8px;height:8px/,'small visible indicator dots');
assert.match(css,/width:40px;height:44px/,'dots retain accessible touch targets');
assert.match(css,/@keyframes bwd-welcome-enter/);
assert.match(css,/@keyframes bwd-welcome-gradient/);
assert.match(css,/@keyframes bwd-welcome-light/);
assert.match(css,/\.app-welcome,\.app-welcome::after\{animation:none!important\}/,'reduced-motion disables hero effects');
assert(Number(worker.match(/const VERSION='bwd-public-shell-2569-11-15-v(\d+)/)?.[1])>=13,'PWA shell version remains at v1.5 or later');
assert.match(workflow,/node tests\/app-ux-v15\.test\.mjs/);
assert.doesNotMatch(app,/https:\/\/drive\.google\.com\/uc\?/,'no private image preview hotlinks');
console.log('PASS Mobile UX v1.5 static contract checks; live iPhone/PWA gesture QA NOT RUN');
