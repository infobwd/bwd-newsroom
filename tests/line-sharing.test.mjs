import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const kit=require('../assets/share.js');
const catalog=JSON.parse(read('data/catalog.json'));
const site='https://infobwd.github.io/bwd-newsroom/';
assert.equal(catalog.schema_version,1);
for(const issue of catalog.issues){
 assert.equal(issue.status,'published');
 assert.ok(issue.visibility_approved_at&&issue.published_at);
 const url=kit.issueUrl(issue,site);
 assert.equal(url,site+'share/'+issue.id+'.html');
 const message=kit.message(issue,site);
 assert(message.includes(issue.title_th));
 assert(message.includes(issue.excerpt_th));
 assert(message.includes(issue.id+'.html'));
 assert(message.includes('พฤศจิกายน 2569'));
 const line=kit.lineTextUrl(issue,site);
 assert(line.startsWith('https://line.me/R/share?text='));
 assert.equal(decodeURIComponent(line.split('?text=')[1]),message);
 const html=read('share/'+issue.id+'.html');
 assert(html.includes('property="og:title"'));
 assert(html.includes('property="og:description"'));
 assert(html.includes('property="og:image"'));
 assert(html.includes(site+issue.pages[0].web_image));
 assert(html.includes('window.location.replace'));
 const image=path.join(root,issue.pages[0].web_image);
 assert(fs.existsSync(image),'source image is published on Pages');
}
const runtime=read('assets/app.js');
const share=read('assets/share.js');
assert.match(read('index.html'),/assets\/share\.js/);
assert(runtime.indexOf("moreOptions.prepend(read)")>=0); // Reader in secondary tools
assert.match(runtime,/shareKit\.prepareFiles\(issue\)/);
assert.match(runtime,/shareKit\.shareFiles\(issue,files\)/);
assert.match(runtime,/shareKit\.lineTextUrl\(issue\)/);
assert.match(runtime,/shareKit\.copyText\(shareKit\.message\(issue\)\)/);
assert.match(share,/canvas\.toBlob\(/);
assert.match(share,/new File\(/);
assert.match(share,/navigator\.canShare/);
assert.match(share,/navigator\.share\(/);
assert.match(share,/https:\/\/line\.me\/R\/share\?text=/);
assert.doesNotMatch(share,/line:\/\/|channel_secret|access_token|private_drive/i);
const worker=read('sw.js');
assert(worker.includes("'./assets/share.js'"));
assert(!worker.slice(worker.indexOf('const SHELL='),worker.indexOf('const PATHS=')).includes('share/WDNEWS'),'No public media previews should be cached');
console.log('PASS LINE share source contracts and approved-only OG links (not LINE device QA)');
