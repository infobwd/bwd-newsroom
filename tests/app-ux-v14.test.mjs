import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const app=read('assets/app.js'), css=read('assets/app-shell.css');
const base=read('assets/styles.css'), worker=read('sw.js');
const workflow=read('.github/workflows/static-qa.yml');
const catalogue=JSON.parse(read('data/catalog.json'));
const approved=catalogue.issues.filter(issue=>issue.status==='published'&&issue.visibility_approved_at&&issue.approved_version&&issue.published_at);
assert(approved.length>0,'published catalogue fixture missing');
assert.match(app,/published\.slice\(0,5\)/,'mobile preview is capped to five');
assert.match(app,/track\.append\(card\)/,'all cards append to horizontal track');
assert.match(app,/track\.addEventListener\('scroll'/,'position updates on native touch scroll');
assert.match(app,/track\.addEventListener\('keydown'/,'keyboard arrows are supported');
assert.match(app,/holder\.append\(controls\)/,'position and direction controls added');
assert.match(app,/addEventListener\('click',e=>\{e\.preventDefault\(\);openIssue/,'entire issue card opens existing detail dialog');
assert.match(css,/scroll-snap-type:x mandatory/);
assert.match(css,/overscroll-behavior-x:contain/);
assert.match(css,/\.app-carousel-dot/,'v1.5 dot indicator replaces the earlier numeric pager');
assert(css.includes('.app-latest-track::-webkit-scrollbar{display:none}'));
assert.match(app,/function lockIssueBackground\(\)/);
assert.match(app,/function unlockIssueBackground\(\)/);
assert.match(app,/lockIssueBackground\(\);[\s\S]*?dialog\.showModal\(\)/,'freeze background before showing dialog');
assert.match(app,/dialog\.addEventListener\('close',[\s\S]*?unlockIssueBackground\(\)/,'restore on close, Escape or history');
assert.match(app,/window\.scrollTo\(0, savedY\)/,'scroll location preserved');
assert.match(base,/body\.newsroom-page\.issue-background-locked/);
assert.match(base,/html\.issue-overlay-open\{overflow:hidden/);
assert.match(base,/#issue-dialog \.dialog-content\{overscroll-behavior-y:contain\}/);
assert(Number(worker.match(/const VERSION='bwd-public-shell-2569-11-15-v(\d+)/)?.[1])>=12,'PWA shell version stays at v1.4 or later');
assert.match(workflow,/node tests\/app-ux-v14\.test\.mjs/);
assert.doesNotMatch(app,/drive\.google\.com\/uc\?/i,'no private Drive image hotlinks');
console.log('Mobile UX v1.4 static contracts PASS; physical iPhone touch/scroll QA NOT RUN');
