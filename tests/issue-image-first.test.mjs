const shell=sw.slice(sw.indexOf('const SHELL='),sw.indexOf('const PATHS='));
assert.doesNotMatch(shell,/assets\/issues\/|assets\/galleries\/|data\/|\.pdf/);
assert.match(workflow,/node tests\/issue-image-first\.test\.mjs/);
