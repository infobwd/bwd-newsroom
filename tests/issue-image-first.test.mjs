/* Source-only issue image-first UX checks; physical Safari/PWA QA is separate. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const app=read('assets/app.js'),home=read('index.html');
const css=read('assets/styles.css'),sw=read('sw.js');
const workflow=read('.github/workflows/static-qa.yml');
const open=app.slice(app.indexOf('  function openIssue('),app.indexOf('  function routeHash()'));
assert(open.length>1000,'issue view exists');
assert.match(home,/id="issue-dialog" aria-labelledby="dialog-title"/);
assert.match(home,/id="dialog-tools" class="dialog-tools"/);
assert.match(home,/summary aria-label="เมนูเพิ่มเติมสำหรับจดหมายข่าว"/);
assert(home.indexOf('id="dialog-tools-options"')<home.indexOf('id="dialog-actions"'));
assert.match(open,/const more=\$\('dialog-tools'\)/);
assert.match(open,/\$\('dialog-tools'\)\.open = false/);
assert.match(open,/moreOptions\.replaceChildren\(\)/);
assert.match(open,/moreOptions\.append\(line\)/);
assert.match(open,/moreOptions\.append\(downloadImage\)/);
assert.match(open,/moreOptions\.append\(copy\)/);
assert.match(open,/moreOptions\.prepend\(read\)/);
assert.match(open,/moreOptions\.append\(a\)/,'optional PDF available');
assert.match(open,/actions\.append\(photoShare, closeMobile, status\)/);
assert.equal((open.match(/actions\.append\(/g)||[]).length,1,'one footer append with share and close');
assert.match(open,/closeMobile\.addEventListener\('click', \(\) => dialog\.close\(\)\)/);
assert.doesNotMatch(open,/actions\.append\(line\)|actions\.prepend\(read\)|actions\.append\(more/);
assert.match(open,/shareKit\.shareFiles\(issue,files\)/);
assert.match(open,/window\.location\.assign\(shareKit\.lineTextUrl\(issue\)\)/);
assert.match(open,/แชร์ข้อความข่าว \(ไม่แนบภาพ\)/);
assert.match(open,/requestToken!==activeIssueRequest/);
assert.doesNotMatch(app,/issueContent\.addEventListener\('scroll',syncIssueHeading/);
assert.doesNotMatch(app,/issue-title-collapsed/,'heading must stay the same height while reading');
assert.match(open,/image\.width = 794; image\.height = 1123/);
assert.match(open,/image\.loading = pageIndex === 0 \? 'eager' : 'lazy'/);
assert.match(css,/#issue-dialog \.dialog-actions \.dialog-close-mobile/);
assert.match(css,/grid-template-columns:minmax\(0,1fr\) 96px/);
assert.match(css,/font-size:16px;line-height:1\.7/);
assert.match(css,/#issue-dialog \.dialog-tools-options/);
assert.match(css,/#issue-dialog \.dialog-actions \.dialog-share-primary/);
assert.match(css,/padding:8px 15px calc\(8px \+ env\(safe-area-inset-bottom\)\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
